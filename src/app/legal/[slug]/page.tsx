export function generateStaticParams() {
  return Object.keys(DOCS).map((slug) => ({ slug }));
}

export async function generateMetadata({ params }: { params: Promise<{ slug: string }> }): Promise<Metadata> {
  const { slug } = await params;
  return { title: DOCS[slug]?.title ?? "Документ" };
}

export default async function LegalPage({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  const doc = DOCS[slug];
  if (!doc) notFound();

  return (
    <article className="mx-auto max-w-3xl space-y-6">
      <h1 className="font-display text-3xl font-extrabold">{doc.title}</h1>
      <Notice tone="warn">
        Черновик для демонстрационной версии. Перед запуском для публики текст должен быть проверен юристом и приведён в соответствие с законодательством Республики Узбекистан. Не является юридической консультацией.
      </Notice>
      {doc.sections.map((s) => (
        <section key={s.h} className="space-y-2">
          <h2 className="font-display text-lg font-semibold">{s.h}</h2>
          {s.p.map((t, i) => (
            <p key={i} className="text-[15px] leading-relaxed text-ink/85">{t}</p>
          ))}
        </section>
      ))}
      <nav className="flex flex-wrap gap-3 border-t border-line pt-6 text-sm" aria-label="Другие документы">
        {Object.entries(DOCS).filter(([k]) => k !== slug).map(([k, d]) => (
          <Link key={k} href={`/legal/${k}`} className="text-accent hover:underline">{d.title}</Link>
        ))}
      </nav>
    </article>
  );
}
